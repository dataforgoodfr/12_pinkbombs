import os
from decimal import Decimal
from secrets import token_hex
from uuid import uuid4

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url
from sqlalchemy.exc import DBAPIError

from pinkbombs_api.database import IdempotencyConflict, SubmissionRepository
from pinkbombs_api.submission_service import SubmissionService
from pinkbombs_api.submission_schemas import SubmissionRequest


@pytest.fixture(params=["reponses_pinkometre_fk", "reponses_pinkometre_id"])
def postgres_repository(request):
    database_url = os.getenv("TEST_DATABASE_URL")
    if not database_url:
        pytest.skip("Set TEST_DATABASE_URL to a disposable PostgreSQL database")
    database_name = make_url(database_url).database or ""
    if not database_name.startswith("test_"):
        pytest.fail(
            "Refusing integration tests unless TEST_DATABASE_URL targets a test_* database"
        )

    schema_name = f"pinkbombs_test_{uuid4().hex[:12]}"
    api_role = f"pb_api_test_{uuid4().hex[:12]}"
    api_password = token_hex(32)
    foreign_key = request.param
    owner_engine = create_engine(database_url)
    with owner_engine.begin() as connection:
        connection.execute(text(f'CREATE SCHEMA "{schema_name}"'))
        connection.execute(text(f'CREATE SCHEMA "{schema_name}_api"'))
        connection.execute(text(f"""CREATE TABLE "{schema_name}".reponses_pinkometre (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email text,
                    impact_initial text,
                    impact_apres_engagement text,
                    alternative_choisie text,
                    supplement_choisi text,
                    consentement_omega3 boolean DEFAULT false
                )"""))
        connection.execute(text(f"""CREATE TABLE "{schema_name}".consommations (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "{foreign_key}" integer NOT NULL REFERENCES
                        "{schema_name}".reponses_pinkometre(id),
                    scenario text NOT NULL CHECK (scenario IN ('Initiale', 'Après engagement')),
                    produit text,
                    variante text,
                    frequence text,
                    occurence_par_an numeric(30, 10),
                    quantite_par_occurrence numeric(30, 10),
                    unite_fr text,
                    poids_annuel_kg numeric(30, 10)
                )"""))
        connection.execute(text(f"""CREATE TABLE "{schema_name}_api".idempotency_keys (
                    key_hash varchar(64) PRIMARY KEY,
                    request_hash varchar(64) NOT NULL,
                    response_id integer NOT NULL,
                    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
                )"""))
        connection.execute(
            text(f"""CREATE ROLE "{api_role}" WITH LOGIN PASSWORD '{api_password}'
                    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT""")
        )
        connection.execute(
            text(f'GRANT USAGE ON SCHEMA "{schema_name}" TO "{api_role}"')
        )
        connection.execute(
            text(f'GRANT USAGE ON SCHEMA "{schema_name}_api" TO "{api_role}"')
        )
        connection.execute(
            text(
                f'''GRANT INSERT (email, impact_initial, impact_apres_engagement,
                    alternative_choisie, supplement_choisi, consentement_omega3),
                    SELECT (id) ON TABLE "{schema_name}".reponses_pinkometre TO "{api_role}"'''
            )
        )
        connection.execute(
            text(f'''GRANT INSERT ("{foreign_key}", scenario, produit, variante,
                    frequence, occurence_par_an, quantite_par_occurrence, unite_fr,
                    poids_annuel_kg), SELECT (id) ON TABLE "{schema_name}".consommations
                    TO "{api_role}"''')
        )
        connection.execute(
            text(
                f"GRANT SELECT, INSERT, DELETE ON TABLE "
                f'"{schema_name}_api".idempotency_keys TO "{api_role}"'
            )
        )
        connection.execute(
            text(
                f'GRANT USAGE ON ALL SEQUENCES IN SCHEMA "{schema_name}" TO "{api_role}"'
            )
        )
        connection.execute(
            text(
                f'ALTER ROLE "{api_role}" SET search_path TO "{schema_name}", "{schema_name}_api"'
            )
        )

    api_url = (
        make_url(database_url)
        .set(
            username=api_role,
            password=api_password,
        )
        .update_query_dict(
            {"options": f"-csearch_path={schema_name},{schema_name}_api"}
        )
    )
    api_engine = create_engine(api_url)
    repository = SubmissionRepository(
        api_engine, idempotency_schema=f"{schema_name}_api"
    )
    repository.test_owner_engine = owner_engine
    repository.test_schema = schema_name
    try:
        yield repository
    finally:
        api_engine.dispose()
        with owner_engine.begin() as connection:
            connection.execute(text(f'DROP SCHEMA "{schema_name}" CASCADE'))
            connection.execute(text(f'DROP SCHEMA "{schema_name}_api" CASCADE'))
            connection.execute(text(f'DROP OWNED BY "{api_role}"'))
            connection.execute(text(f'DROP ROLE "{api_role}"'))
        owner_engine.dispose()


def test_parent_children_and_idempotency_are_atomic(postgres_repository):
    service = SubmissionService(postgres_repository, "a" * 40)
    request = SubmissionRequest.model_validate(
        {
            "response": {"email": "integration@example.org", "impact_initial": "low"},
            "consommations": [
                {
                    "scenario": "initial",
                    "occurence_par_an": "17.125",
                    "unite_fr": "piece",
                },
                {"scenario": "afterCommitment", "produit": "sushi"},
            ],
        }
    )
    key = uuid4()

    result = service.submit(request, key)
    replay = service.submit(request, key)

    assert result.response_id == replay.response_id
    assert result.replayed is False
    assert replay.replayed is True
    schema = postgres_repository.test_schema
    with postgres_repository.test_owner_engine.connect() as connection:
        assert (
            connection.execute(
                text(f'SELECT count(*) FROM "{schema}".reponses_pinkometre')
            ).scalar_one()
            == 1
        )
        children = connection.execute(
            text(
                f'SELECT scenario, occurence_par_an FROM "{schema}".consommations ORDER BY id'
            )
        ).all()
    assert [(row.scenario, row.occurence_par_an) for row in children] == [
        ("Initiale", Decimal("17.1250000000")),
        ("Après engagement", None),
    ]


def test_conflicting_idempotency_key_does_not_duplicate_rows(postgres_repository):
    service = SubmissionService(postgres_repository, "b" * 40)
    first = SubmissionRequest.model_validate(
        {"response": {}, "consommations": [{"scenario": "initial"}]}
    )
    changed = SubmissionRequest.model_validate(
        {
            "response": {"consentement_omega3": True},
            "consommations": [{"scenario": "initial"}],
        }
    )
    key = uuid4()

    service.submit(first, key)
    with pytest.raises(IdempotencyConflict):
        service.submit(changed, key)
    schema = postgres_repository.test_schema
    with postgres_repository.test_owner_engine.connect() as connection:
        assert (
            connection.execute(
                text(f'SELECT count(*) FROM "{schema}".reponses_pinkometre')
            ).scalar_one()
            == 1
        )
        assert (
            connection.execute(
                text(f'SELECT count(*) FROM "{schema}".consommations')
            ).scalar_one()
            == 1
        )


def test_child_constraint_failure_rolls_back_parent(postgres_repository):
    values = {"consentement_omega3": False}
    children = [{"scenario": "invalid"}]

    with pytest.raises(DBAPIError) as error:
        postgres_repository.submit(values, children, "c" * 64, "d" * 64)
    assert (
        getattr(error.value.orig, "sqlstate", None)
        or getattr(error.value.orig, "pgcode", None)
    ) == "23514"
    schema = postgres_repository.test_schema
    with postgres_repository.test_owner_engine.connect() as connection:
        assert (
            connection.execute(
                text(f'SELECT count(*) FROM "{schema}".reponses_pinkometre')
            ).scalar_one()
            == 0
        )
        assert (
            connection.execute(
                text(f'SELECT count(*) FROM "{schema}".consommations')
            ).scalar_one()
            == 0
        )


def test_api_role_cannot_read_or_modify_submission_rows(postgres_repository):
    for statement in [
        "SELECT email FROM reponses_pinkometre",
        "UPDATE reponses_pinkometre SET email = 'changed'",
        "DELETE FROM consommations",
    ]:
        with pytest.raises(DBAPIError) as error:
            with postgres_repository.engine.begin() as connection:
                connection.execute(text(statement))
        assert error.value.orig.pgcode == "42501"
